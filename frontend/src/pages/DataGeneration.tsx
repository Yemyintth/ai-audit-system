import { useEffect, useState } from 'react';
import { Database, Users, TrendingUp, DollarSign, RefreshCw } from 'lucide-react';
import { fetchGenerationStats, fetchBots } from '../api';
import LoadingSpinner from '../components/LoadingSpinner';
import StatCard from '../components/StatCard';

export default function DataGeneration() {
  const [stats, setStats] = useState<any>(null);
  const [bots, setBots] = useState<any>(null);
  const [loading, setLoading] = useState(true);

  const load = async () => {
    setLoading(true);
    try {
      const [s, b] = await Promise.all([fetchGenerationStats(), fetchBots()]);
      setStats(s.data);
      setBots(b.data);
    } catch (e) { console.error(e); }
    finally { setLoading(false); }
  };

  useEffect(() => { load(); }, []);

  if (loading) return <LoadingSpinner message="Loading data generation info..." />;

  return (
    <div className="space-y-6 animate-slide-up">
      <div className="flex justify-between items-center flex-wrap gap-4">
        <div>
          <h2 className="text-3xl font-bold flex items-center gap-3 text-slate-800">
            <Database size={32} /> Data Generation
          </h2>
          <p className="text-slate-500 mt-1">Synthetic accounting data created by bots</p>
        </div>
        <button onClick={load} className="btn btn-primary"><RefreshCw size={16} /> Refresh</button>
      </div>

      <div className="grid grid-cols-1 md:grid-cols-4 gap-4">
        <StatCard label="Total Accounts" value={stats?.accounts?.toLocaleString() || 0} icon={Users} color="blue" trend="Generated by Normal Bot" />
        <StatCard label="Total Transactions" value={stats?.transactions?.toLocaleString() || 0} icon={Database} color="green" trend="Across all accounts" />
        <StatCard label="Total Amount" value={'$' + (stats?.total_amount || 0).toLocaleString(undefined, { maximumFractionDigits: 0 })} icon={DollarSign} color="orange" trend="Money flow" />
        <StatCard label="Avg Amount" value={'$' + (stats?.avg_amount || 0).toLocaleString()} icon={TrendingUp} color="blue" trend="Per transaction" />
      </div>

      <div className="card bg-gradient-to-r from-blue-50 to-slate-50 border-blue-200">
        <h3 className="font-semibold text-lg mb-2">Data Source</h3>
        <div className="grid grid-cols-2 md:grid-cols-4 gap-4 text-sm">
          <div><div className="text-slate-500">Type</div><div className="font-semibold">{stats?.data_source}</div></div>
          <div><div className="text-slate-500">Generated</div><div className="font-semibold">{stats?.generation_date}</div></div>
          <div><div className="text-slate-500">Anomaly Rate</div><div className="font-semibold text-red-600">{bots?.anomaly_rate}%</div></div>
          <div><div className="text-slate-500">Total Anomalies</div><div className="font-semibold text-red-600">{bots?.total_anomalies?.toLocaleString()}</div></div>
        </div>
      </div>

      <div className="card">
        <h3 className="font-semibold text-lg mb-4">Bot Activity Summary</h3>
        <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
          <div className="p-4 bg-blue-50 rounded-lg border border-blue-200">
            <div className="font-bold text-blue-800">{bots?.normal_bot?.name}</div>
            <div className="text-sm text-slate-600 mt-1">{bots?.normal_bot?.description}</div>
            <div className="mt-3 grid grid-cols-2 gap-2 text-xs">
              <div><span className="text-slate-500">Accounts:</span> <span className="font-semibold">{bots?.normal_bot?.accounts_created?.toLocaleString()}</span></div>
              <div><span className="text-slate-500">Txns:</span> <span className="font-semibold">{bots?.normal_bot?.transactions_created?.toLocaleString()}</span></div>
              <div><span className="text-slate-500">Hours:</span> <span className="font-semibold">{bots?.normal_bot?.business_hours}</span></div>
              <div><span className="text-slate-500">Avg:</span> <span className="font-semibold">${bots?.normal_bot?.avg_amount}</span></div>
            </div>
          </div>
          <div className="p-4 bg-red-50 rounded-lg border border-red-200">
            <div className="font-bold text-red-800">{bots?.anomaly_bot?.name}</div>
            <div className="text-sm text-slate-600 mt-1">{bots?.anomaly_bot?.description}</div>
            <div className="mt-3 grid grid-cols-2 gap-2 text-xs">
              <div><span className="text-slate-500">Targeted:</span> <span className="font-semibold">{bots?.anomaly_bot?.accounts_targeted?.toLocaleString()}</span></div>
              <div><span className="text-slate-500">Anomalies:</span> <span className="font-semibold">{bots?.anomaly_bot?.transactions_created?.toLocaleString()}</span></div>
              <div><span className="text-slate-500">Types:</span> <span className="font-semibold">{bots?.anomaly_bot?.anomaly_types?.length}</span></div>
              <div><span className="text-slate-500">Status:</span> <span className="font-semibold text-green-600">{bots?.anomaly_bot?.status}</span></div>
            </div>
          </div>
        </div>
      </div>
    </div>
  );
}
